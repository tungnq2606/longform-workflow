"""Hero kits: approved images of one important character, shared by every video.

library/characters/<id>/kit.json
  {"id", "name", "height" (on-screen px at scale 1 on the 1440p frame), "model_sheet" (optional),
   "images": {"<pose>.<expression>": {"file", "anchor": [x, y], "size": [w, h], "blink" (optional)}}}

  python -m tools.longform.kit add <id> <pose.expr> <raw.png> [--blink raw_blink.png] [--name "..."] [--height 620]
  python -m tools.longform.kit validate <id>
  python -m tools.longform.kit ts        writes tools/anim/src/longform/kits.generated.ts (refuses kits with problems)
"""
import argparse
import glob
import json
import os
import sys

from PIL import Image

from tools.longform import cutout, paths

REQUIRED = ("id", "name", "height", "images")
TS_OUT = os.path.join(paths.WS, "tools", "anim", "src", "longform", "kits.generated.ts")


def kit_dir(kit_id):
    return os.path.join(paths.library(), "characters", kit_id)


def load_kit(kit_id):
    with open(os.path.join(kit_dir(kit_id), "kit.json"), encoding="utf-8") as f:
        return json.load(f)


def _save(kit_id, k):
    with open(os.path.join(kit_dir(kit_id), "kit.json"), "w", encoding="utf-8") as f:
        json.dump(k, f, ensure_ascii=False, indent=1)


def validate_kit(kdir):
    p = os.path.join(kdir, "kit.json")
    if not os.path.exists(p):
        return ["missing kit.json"]
    k = json.load(open(p, encoding="utf-8"))
    problems = ["kit.json has no '%s'" % key for key in REQUIRED if key not in k]
    if problems:
        return problems
    if not k["images"]:
        problems.append("kit has no images")
    for key, im in k["images"].items():
        f = os.path.join(kdir, im["file"])
        if not os.path.exists(f):
            problems.append("%s: missing %s" % (key, im["file"]))
            continue
        problems += ["%s: %s" % (key, x) for x in cutout.check(f)]
        w, h = Image.open(f).size
        ax, ay = im.get("anchor", [-1, -1])
        if not (0 <= ax < w and 0 <= ay < h):
            problems.append("%s: anchor %s outside the %dx%d image" % (key, im.get("anchor"), w, h))
        if im.get("blink"):
            b = os.path.join(kdir, im["blink"])
            if not os.path.exists(b):
                problems.append("%s: blink missing %s" % (key, im["blink"]))
            elif Image.open(b).size != (w, h):
                problems.append("%s: blink image is %dx%d, pose is %dx%d" % ((key,) + Image.open(b).size + (w, h)))
    return problems


def add_image(kit_id, key, raw_src, blink_src=None, name=None, height=None):
    d = kit_dir(kit_id)
    os.makedirs(d, exist_ok=True)
    k = load_kit(kit_id) if os.path.exists(os.path.join(d, "kit.json")) else {"id": kit_id, "images": {}}
    if name:
        k["name"] = name
    if height:
        k["height"] = height
    base = key.replace(".", "_")
    info = cutout.cut(raw_src, os.path.join(d, base + ".png"))
    entry = {"file": base + ".png", "anchor": info["anchor"], "size": [info["width"], info["height"]]}
    if blink_src:  # same crop box and key as the pose, so both images line up pixel for pixel
        entry["blink"] = base + "_blink.png"
        cutout.cut(blink_src, os.path.join(d, entry["blink"]), box=info["box"], key=info["key"])
    k["images"][key] = entry
    _save(kit_id, k)
    return validate_kit(d)


def write_ts(out=TS_OUT):
    kits, keys, bad = {}, [], []
    for kj in sorted(glob.glob(os.path.join(paths.library(), "characters", "*", "kit.json"))):
        d = os.path.dirname(kj)
        probs = validate_kit(d)
        if probs:
            bad.append("%s: %s" % (os.path.basename(d), "; ".join(probs)))
            continue
        k = json.load(open(kj, encoding="utf-8"))
        rel = "library/characters/%s/" % k["id"]
        kits[k["id"]] = {"name": k["name"], "height": k["height"], "images": {
            key: {"file": rel + im["file"], "anchor": im["anchor"], "size": im["size"],
                  **({"blink": rel + im["blink"]} if im.get("blink") else {})} for key, im in k["images"].items()}}
        keys += ["'%s/%s'" % (k["id"], key) for key in k["images"]]
    if bad:
        sys.exit("kits with problems (fix them first):\n" + "\n".join(bad))
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by `python -m tools.longform.kit ts` from library/characters/*/kit.json. Do not edit.\n")
        f.write("export const KITS = %s as const;\n\n" % json.dumps(kits, ensure_ascii=False, indent=1))
        f.write("export type HeroKey = %s;\n" % (" | ".join(keys) if keys else "never"))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("add")
    a.add_argument("id")
    a.add_argument("key")
    a.add_argument("raw")
    a.add_argument("--blink")
    a.add_argument("--name")
    a.add_argument("--height", type=int)
    v = sub.add_parser("validate")
    v.add_argument("id")
    sub.add_parser("ts")
    o = ap.parse_args()
    if o.cmd == "add":
        probs = add_image(o.id, o.key, o.raw, o.blink, o.name, o.height)
    elif o.cmd == "validate":
        probs = validate_kit(kit_dir(o.id))
    else:
        write_ts()
        probs = []
    print("\n".join(probs) if probs else "ok")
    sys.exit(1 if probs else 0)


if __name__ == "__main__":
    main()
