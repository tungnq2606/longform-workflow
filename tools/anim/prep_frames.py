#!/usr/bin/env python3
"""Prepare a video made of generated images (images/frames/*.png) for the Remotion "Frames" composition.

Usage: prep_frames.py VIDEO_DIR

Reads images/prompts/manifest.json (scene order and frame files), images/shots.json (block, sentence, frac,
optional overlays; optional top-level "chapters" {"2": "The math"} and "cuts" {"10": [[6, 8]]}) and the voice
files. Writes images/frames_timeline.json, render/subtitles.srt and tools/anim/src/current_frames.ts.
A frame starts when its sentence starts in the voice file and lasts until the next frame.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "kit"))
from storyboard import CARD, GAP, sentence_starts  # noqa: E402

if len(sys.argv) < 2:
    sys.exit(__doc__)
V = os.path.abspath(sys.argv[1])
img = os.path.join(V, "images")
man = json.load(open(os.path.join(img, "prompts", "manifest.json"), encoding="utf-8"))["items"]
spec = json.load(open(os.path.join(img, "shots.json"), encoding="utf-8"))
shots = {s["id"]: s for s in spec["shots"]}
chapters = {int(k): v for k, v in spec.get("chapters", {}).items()}
cuts_by = {int(k): v for k, v in spec.get("cuts", {}).items()}

nums = sorted(int(f[:2]) for f in os.listdir(os.path.join(V, "audio")) if re.fullmatch(r"\d\d\.mp3", f))
if not nums:
    sys.exit("no voice files in audio/ (01.mp3, 02.mp3, ...)")
blocks, t, subs = {}, 0.0, []
for num in nums:
    sents, starts, dur = sentence_starts(V, num)
    card = CARD if num in chapters else 0.0
    gap = 0.0 if (num + 1) in chapters or num == nums[-1] else GAP
    cut = [(starts[a - 1], starts[b - 1] if b <= len(starts) else dur) for a, b in cuts_by.get(num, [])]
    gone = {i for a, b in cuts_by.get(num, []) for i in range(a, b)}

    def out(x, cut=cut):
        return x - sum(min(max(x - a, 0), b - a) for a, b in cut)
    eff = [out(x) for x in starts]
    dur_eff = out(dur)
    blocks[num] = {"n": num, "audio": "audio/%02d.mp3" % num, "start": round(t, 3), "card": card, "dur": round(dur_eff, 3),
                   "gap": gap, "starts": [round(x, 3) for x in eff], "cuts": [[round(a, 3), round(b, 3)] for a, b in cut]}
    for i, s in enumerate(sents):
        if i + 1 not in gone:
            a = t + card + eff[i]
            b = t + card + (eff[i + 1] if i + 1 < len(eff) else dur_eff)
            subs.append((a, max(b - 0.05, a + 0.5), s))
    t += card + dur_eff + gap

frames, missing = [], []
for it in man:
    if it["kind"] != "scene":
        continue
    sh = shots[it["id"]]
    if not os.path.exists(os.path.join(img, it["save_as"])):
        missing.append(it["id"])
        continue
    b = blocks.get(sh.get("block"))
    if not b:
        sys.exit("shot %s: block %s has no voice file" % (it["id"], sh.get("block")))
    k = sh.get("sentence", 1)
    s0 = b["starts"][k - 1] if k - 1 < len(b["starts"]) else b["dur"]
    s1 = b["starts"][k] if k < len(b["starts"]) else b["dur"]
    at = b["start"] + b["card"] + s0 + sh.get("frac", 0) * (s1 - s0)
    if k == 1 and sh.get("frac", 0) == 0:
        at = b["start"]  # first image of a block also covers its chapter card
    frames.append({"id": it["id"], "file": "images/" + it["save_as"], "from": round(at, 3), "block": b["n"],
                   "overlays": sh.get("overlays", [])})
if missing:
    sys.exit("missing frames (generate or import them first): " + ", ".join(missing))
frames.sort(key=lambda f: f["from"])
for i, f in enumerate(frames):
    f["to"] = frames[i + 1]["from"] if i + 1 < len(frames) else round(t, 3)

order = sorted(chapters)
timeline = {"fps": 30, "total": round(t, 3), "blocks": [blocks[n] for n in nums], "frames": frames,
            "chapters": [{"block": n, "index": order.index(n) + 1, "title": chapters[n], "start": blocks[n]["start"],
                          "card": blocks[n]["card"]} for n in order if n in blocks]}
json.dump(timeline, open(os.path.join(img, "frames_timeline.json"), "w", encoding="utf-8"), indent=1)

pron = os.path.join(V, "script", "pronounce.json")
undo = {v: k for k, v in json.load(open(pron)).items()} if os.path.exists(pron) else {}


def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); mi, ms = divmod(ms, 60000); se, ms = divmod(ms, 1000)
    return "%02d:%02d:%02d,%03d" % (h, mi, se, ms)


cues = []
for a, b, s in subs:
    for k, v in undo.items():
        s = s.replace(k, v)
    cues.append("%d\n%s --> %s\n%s\n" % (len(cues) + 1, ts(a), ts(b), s))
os.makedirs(os.path.join(V, "render"), exist_ok=True)
open(os.path.join(V, "render", "subtitles.srt"), "w", encoding="utf-8").write("\n".join(cues))

relp = os.path.relpath(os.path.join(img, "frames_timeline.json"), os.path.join(HERE, "src")).replace(os.sep, "/")
open(os.path.join(HERE, "src", "current_frames.ts"), "w", encoding="utf-8").write(
    "// Generated by prep_frames.py: the image-based video the Remotion \"Frames\" composition renders.\n"
    "import data from '%s';\nexport const FRAMES = data;\n" % relp)
print("%s: %d frames, %.1f s, chapters %s" % (os.path.basename(V), len(frames), t, order))
