#!/usr/bin/env python3
"""Prepare a video for the Remotion toolkit.

Usage: prep.py videos/NNN-slug

Reads script/voiceover_tts/*.txt and audio/*.mp3, finds where each sentence starts in the
audio (same alignment as the static pipeline), and writes:
  videos/NNN-slug/anim/timing.json   blocks, sentence starts, durations, card/gap layout
  tools/anim/src/current.ts          points the Remotion project at that video's anim/scenes.tsx
  videos/NNN-slug/render/subtitles.srt   one cue per spoken sentence, on the animated timeline

Cuts: `export const CUTS = {10: [[6, 8]]}` in scenes.tsx drops voice block 10 from the start of
sentence 6 to the start of sentence 8 (audio and subtitles); the voice file itself is not changed.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "kit"))
from storyboard import CARD, GAP, sentence_starts  # noqa: E402

if len(sys.argv) < 2:
    sys.exit("usage: prep.py videos/NNN-slug")
V = os.path.abspath(sys.argv[1])
scenes = os.path.join(V, "anim", "scenes.tsx")
if not os.path.exists(scenes):
    sys.exit("no anim/scenes.tsx in " + V)

# Chapter cards are declared in scenes.tsx: export const CHAPTERS = {2: "The math", ...}
src = open(scenes, encoding="utf-8").read()
m = re.search(r"export const CHAPTERS[^=]*=\s*\{([^}]*)\}", src)
chapters = {int(k): v for k, v in re.findall(r"(\d+)\s*:\s*\"([^\"]*)\"", m.group(1))} if m else {}

m = re.search(r"export const CUTS[^=]*=\s*\{(.*?)\};", src, re.S)
cuts_by = {int(k): [(int(a), int(b)) for a, b in re.findall(r"\[(\d+),\s*(\d+)\]", v)]
           for k, v in re.findall(r"(\d+)\s*:\s*(\[\[.*?\]\])", m.group(1))} if m else {}

nums = sorted(int(f[:2]) for f in os.listdir(os.path.join(V, "audio")) if re.fullmatch(r"\d\d\.mp3", f))
blocks, t, subs, chap_times = [], 0.0, [], {}
for num in nums:
    sents, starts, dur = sentence_starts(V, num)
    card = CARD if num in chapters else 0.0
    gap = 0.0 if (num + 1) in chapters or num == nums[-1] else GAP
    # cuts in source seconds; sentences inside a cut get zero length on the timeline
    cut = [(starts[a - 1], starts[b - 1] if b <= len(starts) else dur) for a, b in cuts_by.get(num, [])]
    gone = {i for a, b in cuts_by.get(num, []) for i in range(a, b)}

    def out(x):
        return x - sum(min(max(x - a, 0), b - a) for a, b in cut)
    eff = [out(x) for x in starts]
    dur_eff = out(dur)
    blocks.append({"n": num, "audio": "audio/%02d.mp3" % num, "start": round(t, 3), "card": card,
                   "dur": round(dur_eff, 3), "gap": gap, "starts": [round(x, 3) for x in eff], "sents": sents,
                   "cuts": [[round(a, 3), round(b, 3)] for a, b in cut]})
    for i, snt in enumerate(sents):
        if i + 1 in gone:
            continue
        a = t + card + eff[i]
        b = t + card + (eff[i + 1] if i + 1 < len(eff) else dur_eff)
        subs.append((a, max(b - 0.05, a + 0.5), snt))
    chap_times[num] = t
    t += card + dur_eff + gap

result = {"fps": 30, "total": round(t, 3), "chapters": chapters, "blocks": blocks}
json.dump(result, open(os.path.join(V, "anim", "timing.json"), "w", encoding="utf-8"), indent=1)

# subtitles: one cue per sentence, TTS spellings undone
pron = os.path.join(V, "script", "pronounce.json")
undo = {v: k for k, v in json.load(open(pron)).items()} if os.path.exists(pron) else {}


def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); mi, ms = divmod(ms, 60000); se, ms = divmod(ms, 1000)
    return "%02d:%02d:%02d,%03d" % (h, mi, se, ms)


cues = []
for a, b, snt in subs:
    for k, v in undo.items():
        snt = snt.replace(k, v)
    cues.append("%d\n%s --> %s\n%s\n" % (len(cues) + 1, ts(a), ts(b), snt))
os.makedirs(os.path.join(V, "render"), exist_ok=True)
open(os.path.join(V, "render", "subtitles.srt"), "w", encoding="utf-8").write("\n".join(cues))
print("chapter starts on the animated timeline (check upload texts):",
      ", ".join("%d:%02d" % divmod(int(chap_times[n]), 60) for n in sorted(chap_times) if n == nums[0] or n in chapters))

rel = os.path.relpath(os.path.join(V, "anim"), os.path.join(HERE, "src")).replace(os.sep, "/")
open(os.path.join(HERE, "src", "current.ts"), "w", encoding="utf-8").write(
    "// Generated by prep.py: the video the Remotion project renders.\n"
    f"export {{SCENES, BG, CHAPTERS}} from '{rel}/scenes';\n"
    f"import timing from '{rel}/timing.json';\n"
    "export const TIMING = timing;\n"
    f"export const VIDEO_DIR = '{os.path.basename(V)}';\n")
print("%s: %d blocks, %.1f s, chapters %s" % (os.path.basename(V), len(blocks), t, sorted(chapters)))
